function part(overrides: {
  id: string
  roundId: string
  ordinal: number
  partType: PartRecord['partType']
  roleLabel: string | null
  payload: PartRecord['payload']
  tokens: PartRecord['tokens']
  parentPartId?: string | null
  contextState?: PartRecord['context']['state']
  contextNote?: string | null
  collapsedByDefault?: boolean
  provenanceJson?: unknown
}): PartRecord {
  return {
    id: overrides.id,
    sessionId,
    turnId,
    roundId: overrides.roundId,
    parentPartId: overrides.parentPartId ?? null,
    ordinal: overrides.ordinal,
    partType: overrides.partType,
    roleLabel: overrides.roleLabel,
    payload: overrides.payload,
    display: {
      state: 'transcript',
      collapsedByDefault: overrides.collapsedByDefault ?? false,
    },
    context: {
      state: overrides.contextState ?? 'included',
      note: overrides.contextNote ?? null,
      strippedByCompactionAtTurnId: null,
    },
    tokens: overrides.tokens,
    provenanceJson: overrides.provenanceJson ?? null,
    createdAt: overrides.ordinal,
    updatedAt: overrides.ordinal,
  }
}

